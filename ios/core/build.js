'use strict';
// Bundles ios/core/app-core.js and everything it requires (src/sync, src/cloud, src/store.js,
// src/backups.js, src/renderer/sync-apply.js, ios/core/board.js) into one script for JavaScriptCore:
// ios/Recaller/Resources/core/recaller-core.js. Node's modules become the shims in ios/core/shims.
// The desktop's files are used as they are, so a fix there reaches the iPhone at its next build.
//
//   node ios/core/build.js            → writes the bundle (and copies src/cloud/project.json next to it)
//   node ios/core/build.js --check    → only checks that it bundles

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const ENTRY = 'ios/core/app-core.js';
const OUT_DIR = path.join(ROOT, 'ios/Recaller/Resources/core');
const OUT = path.join(OUT_DIR, 'recaller-core.js');
const SHIMS = {
  fs: 'ios/core/shims/fs.js',
  path: 'ios/core/shims/path.js',
  crypto: 'ios/core/shims/crypto.js',
  os: 'ios/core/shims/os.js',
  util: 'ios/core/shims/util.js',
  electron: 'ios/core/shims/electron.js',
};
const REQUIRE = /\brequire\(\s*(['"])([^'"]+)\1\s*\)/g;

function resolve(fromId, spec) {
  const bare = spec.replace(/^node:/, '');
  if (SHIMS[bare]) return SHIMS[bare];
  if (!spec.startsWith('.')) throw new Error(`${fromId}: no shim for '${spec}'`);
  const base = path.posix.normalize(path.posix.join(path.posix.dirname(fromId), spec));
  for (const c of [base, `${base}.js`, `${base}/index.js`]) {
    const abs = path.join(ROOT, c);
    if (fs.existsSync(abs) && fs.statSync(abs).isFile()) return c;
  }
  throw new Error(`${fromId}: can't find '${spec}'`);
}

function collect() {
  const mods = new Map();
  const queue = [ENTRY];
  while (queue.length) {
    const id = queue.shift();
    if (mods.has(id)) continue;
    const src = fs.readFileSync(path.join(ROOT, id), 'utf8');
    const map = {};
    for (const m of src.matchAll(REQUIRE)) {
      const spec = m[2];
      if (map[spec]) continue;
      // A require inside a comment line (docs) is skipped.
      const lineStart = src.lastIndexOf('\n', m.index) + 1;
      if (/^\s*(\/\/|\*)/.test(src.slice(lineStart, m.index))) continue;
      map[spec] = resolve(id, spec);
      queue.push(map[spec]);
    }
    mods.set(id, { src, map });
  }
  return mods;
}

function bundle() {
  const mods = collect();
  const parts = [];
  parts.push('// Generated by ios/core/build.js from the files named below. Do not edit.');
  parts.push('(function () {');
  parts.push('var __root = (globalThis.__moduleRoot || "");');
  parts.push('var __defs = {};');
  parts.push('var __maps = {};');
  for (const [id, { src, map }] of mods) {
    const body = src.replace(/^#!.*\n/, '');
    parts.push(`// ---- ${id}`);
    parts.push(`__maps[${JSON.stringify(id)}] = ${JSON.stringify(map)};`);
    parts.push(`__defs[${JSON.stringify(id)}] = function (module, exports, require, __filename, __dirname) {\n${body}\n};`);
  }
  parts.push(`var __cache = {};
function __req(id) {
  var hit = __cache[id];
  if (hit) return hit.exports;
  var module = { exports: {} };
  __cache[id] = module;
  var map = __maps[id];
  var dir = id.slice(0, id.lastIndexOf('/'));
  __defs[id].call(module.exports, module, module.exports, function (spec) {
    var target = map[spec];
    if (!target) throw new Error("Cannot find module '" + spec + "' from " + id);
    return __req(target);
  }, __root + '/' + id, __root + '/' + dir);
  return module.exports;
}
__req(${JSON.stringify(ENTRY)});
})();`);
  return { text: parts.join('\n'), ids: [...mods.keys()] };
}

if (require.main === module) {
  const { text, ids } = bundle();
  if (process.argv.includes('--check')) {
    console.log(`ok: ${ids.length} modules, ${(text.length / 1024).toFixed(0)} KB`);
  } else {
    fs.mkdirSync(path.join(OUT_DIR, 'src/cloud'), { recursive: true });
    fs.writeFileSync(OUT, text);
    // The cloud config the desktop build ships (src/cloud/project.json, from Terraform's app_config).
    // It isn't in git; without it the iPhone app has no accounts, like a desktop build without it.
    const project = path.join(ROOT, 'src/cloud/project.json');
    const target = path.join(OUT_DIR, 'src/cloud/project.json');
    if (fs.existsSync(project)) fs.copyFileSync(project, target);
    else {
      fs.rmSync(target, { force: true });
      console.warn('warning: src/cloud/project.json is missing (npm run cloud:config); the app will have no accounts');
    }
    console.log(`wrote ${path.relative(ROOT, OUT)}: ${ids.length} modules, ${(text.length / 1024).toFixed(0)} KB`);
  }
}

module.exports = { bundle, OUT };
